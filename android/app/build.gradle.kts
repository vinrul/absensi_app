// Signing release dibaca dari android/keystore.properties (tidak di-commit).
// Tanpa berkas itu build debug tetap berjalan dan release dihasilkan tanpa tanda tangan.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}

if (keystorePropertiesFile.exists()) {
    val wajib = listOf("storeFile", "storePassword", "keyAlias", "keyPassword")
    val kosong = wajib.filter { keystoreProperties.getProperty(it).isNullOrBlank() }
    if (kosong.isNotEmpty()) {
        error("android/keystore.properties belum lengkap: ${kosong.joinToString(", ")}")
    }
}

